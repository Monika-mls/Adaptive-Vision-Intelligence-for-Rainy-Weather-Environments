
"""
Adaptive Vision Intelligence for Rainy Weather Environments

Phase 3 - Step 13: Binary Rain Severity Inference

Class mapping:
    0 -> Light -> PReNet
    1 -> Heavy -> VDMamba

Features:
    - Load the locally trained best.pt checkpoint
    - No ImageNet checkpoint downloads
    - No training or optimizer operations
    - Consistent ImageNet preprocessing
    - Softmax class probabilities
    - Confidence and uncertainty handling
    - Severity-based restoration routing
    - JSON output
    - CPU and CUDA support

IMPORTANT:
    This module predicts a restoration route.
    It does not execute image restoration.
"""

import argparse
import json
import math
import os
import tempfile
from datetime import datetime, timezone
from pathlib import Path

import torch
from PIL import Image, UnidentifiedImageError
from torchvision.models import MobileNet_V3_Small_Weights

from vision.severity.model import create_severity_model


# ------------------------------------------------------------
# 1. CONSTANTS
# ------------------------------------------------------------

CLASS_NAMES = ("Light", "Heavy")

RESTORATION_ROUTES = {
    "Light": "PReNet",
    "Heavy": "VDMamba",
}

DEFAULT_CHECKPOINT = Path(
    "checkpoints/severity/best.pt"
)

DEFAULT_OUTPUT = Path(
    "docs/severity_prediction.json"
)

PREPROCESSING_NAME = "IMAGENET1K_V1"

# These are exploratory thresholds, not calibrated.
DEFAULT_CONFIDENCE_THRESHOLD = 0.75
DEFAULT_MARGIN_THRESHOLD = 0.20

ALLOWED_IMAGE_SUFFIXES = {
    ".png",
    ".jpg",
    ".jpeg",
}


# ------------------------------------------------------------
# 2. DEVICE SELECTION
# ------------------------------------------------------------

def get_inference_device(name="auto"):
    """Select the device for inference."""

    if name not in ("auto", "cpu", "cuda"):
        raise ValueError(
            "Device must be 'auto', 'cpu' or 'cuda'."
        )

    if name == "auto":
        name = (
            "cuda"
            if torch.cuda.is_available()
            else "cpu"
        )

    if name == "cuda" and not torch.cuda.is_available():
        raise RuntimeError(
            "CUDA was requested but is unavailable."
        )

    return torch.device(name)


# ------------------------------------------------------------
# 3. CHECKPOINT VALIDATION
# ------------------------------------------------------------

def validate_checkpoint(checkpoint):
    """
    Validate metadata and state dictionary before loading.

    Only use checkpoints generated by this project
    and obtained from a trusted source.
    """

    if not isinstance(checkpoint, dict):
        raise ValueError(
            "Checkpoint must be a dictionary."
        )

    required = {
        "model_state_dict",
        "classes",
        "architecture",
        "preprocessing",
    }

    missing = required - set(checkpoint)

    if missing:
        raise ValueError(
            f"Checkpoint fields missing: {sorted(missing)}"
        )

    if checkpoint["architecture"] != "mobilenet_v3_small":
        raise ValueError(
            "Unexpected checkpoint architecture."
        )

    if checkpoint["preprocessing"] != PREPROCESSING_NAME:
        raise ValueError(
            "Checkpoint preprocessing does not match "
            "the supported inference preprocessing."
        )

    if tuple(checkpoint["classes"]) != CLASS_NAMES:
        raise ValueError(
            "Checkpoint class order mismatch. "
            "Expected ['Light', 'Heavy']."
        )

    state = checkpoint["model_state_dict"]

    if not isinstance(state, dict) or not state:
        raise ValueError(
            "Missing or invalid model weights."
        )

    for key, value in state.items():
        if not isinstance(key, str):
            raise ValueError(
                "Invalid state dictionary key."
            )

        if not isinstance(value, torch.Tensor):
            raise ValueError(
                f"Invalid state dictionary value: {key}"
            )

    return True


# ------------------------------------------------------------
# 4. LOAD TRAINED MODEL
# ------------------------------------------------------------

def load_trained_model(
    checkpoint_path=DEFAULT_CHECKPOINT,
    device="auto",
):
    """
    Load the trained binary classifier.

    pretrained=False is intentional:
    the entire trained state dictionary is loaded
    from best.pt, without downloading ImageNet weights.
    """

    checkpoint_path = Path(checkpoint_path)

    if not checkpoint_path.is_file():
        raise FileNotFoundError(
            f"Trained checkpoint not found: {checkpoint_path}"
        )

    selected_device = get_inference_device(device)

    checkpoint = torch.load(
        checkpoint_path,
        map_location="cpu",
        weights_only=True,
    )

    validate_checkpoint(checkpoint)

    model = create_severity_model(
        pretrained=False,
        freeze_backbone=True,
        device="cpu",
    )

    # Strict loading ensures all checkpoint weights
    # match our two-class architecture.
    model.load_state_dict(
        checkpoint["model_state_dict"],
        strict=True,
    )

    model = model.to(selected_device)
    model.eval()

    for parameter in model.parameters():
        parameter.requires_grad_(False)

    metadata = {
        "checkpoint_path": str(
            checkpoint_path.resolve()
        ),
        "architecture": checkpoint["architecture"],
        "classes": list(CLASS_NAMES),
        "preprocessing": checkpoint["preprocessing"],
        "checkpoint_epoch": checkpoint.get("epoch"),
        "checkpoint_best_macro_f1": checkpoint.get(
            "best_macro_f1"
        ),
        "device": str(selected_device),
    }

    return model, selected_device, metadata


# ------------------------------------------------------------
# 5. IMAGE PREPROCESSING
# ------------------------------------------------------------

def preprocess_image(image_path):
    """
    Apply the same torchvision ImageNet transforms
    used by the severity dataset loader.

    The transforms object itself does not download
    pretrained weights.
    """

    image_path = Path(image_path)

    if not image_path.is_file():
        raise FileNotFoundError(
            f"Image not found: {image_path}"
        )

    if (
        image_path.suffix.lower()
        not in ALLOWED_IMAGE_SUFFIXES
    ):
        raise ValueError(
            "Supported formats: PNG, JPG, JPEG."
        )

    try:
        with Image.open(image_path) as opened:
            opened.load()
            image = opened.convert("RGB")

    except (
        OSError,
        UnidentifiedImageError,
        Image.DecompressionBombError,
    ) as error:
        raise ValueError(
            f"Could not decode image: {error}"
        ) from error

    original_size = {
        "width": image.width,
        "height": image.height,
    }

    weights = (
        MobileNet_V3_Small_Weights.IMAGENET1K_V1
    )

    transforms = weights.transforms()

    tensor = transforms(image)

    if tensor.shape != (3, 224, 224):
        raise RuntimeError(
            f"Unexpected preprocessed shape: {tensor.shape}"
        )

    if not torch.isfinite(tensor).all().item():
        raise ValueError(
            "Image preprocessing produced non-finite values."
        )

    return tensor.unsqueeze(0), original_size


# ------------------------------------------------------------
# 6. PREDICTION INTERPRETATION
# ------------------------------------------------------------

def interpret_logits(
    logits,
    confidence_threshold=DEFAULT_CONFIDENCE_THRESHOLD,
    margin_threshold=DEFAULT_MARGIN_THRESHOLD,
):
    """
    Convert two-class logits into prediction metadata.

    For uncertain predictions, the suggested route
    remains visible but automatic execution is blocked.
    """

    if not (0.5 <= confidence_threshold <= 1.0):
        raise ValueError(
            "Confidence threshold must be between "
            "0.5 and 1.0."
        )

    if not (0.0 <= margin_threshold <= 1.0):
        raise ValueError(
            "Margin threshold must be between 0 and 1."
        )

    if logits.shape != (1, 2):
        raise ValueError(
            "Expected logits with shape (1, 2)."
        )

    if not torch.isfinite(logits).all().item():
        raise ValueError(
            "Model logits contain non-finite values."
        )

    probabilities = torch.softmax(
        logits.float(), dim=1
    )[0].detach().cpu()

    predicted_index = int(
        torch.argmax(probabilities).item()
    )

    predicted_class = CLASS_NAMES[predicted_index]

    confidence = float(
        probabilities[predicted_index].item()
    )

    probability_margin = float(
        torch.abs(
            probabilities[0] - probabilities[1]
        ).item()
    )

    low_confidence = (
        confidence < confidence_threshold
    )

    low_margin = (
        probability_margin < margin_threshold
    )

    uncertain = low_confidence or low_margin

    reasons = []

    if low_confidence:
        reasons.append("confidence_below_threshold")

    if low_margin:
        reasons.append("probability_margin_below_threshold")

    suggested_model = RESTORATION_ROUTES[
        predicted_class
    ]

    return {
        "predicted_class": predicted_class,
        "predicted_class_index": predicted_index,
        "confidence": round(confidence, 6),
        "probabilities": {
            CLASS_NAMES[index]: round(
                float(probabilities[index].item()), 6
            )
            for index in range(2)
        },
        "probability_margin": round(
            probability_margin, 6
        ),
        "uncertain": uncertain,
        "uncertainty_reasons": reasons,
        "decision_thresholds": {
            "minimum_confidence": confidence_threshold,
            "minimum_probability_margin": margin_threshold,
            "calibrated": False,
        },
        "suggested_restoration_model": suggested_model,
        "automatic_routing_allowed": not uncertain,
        "restoration_executed": False,
    }


# ------------------------------------------------------------
# 7. PERFORM INFERENCE
# ------------------------------------------------------------

def predict_image(
    image_path,
    model,
    device,
    metadata=None,
    confidence_threshold=DEFAULT_CONFIDENCE_THRESHOLD,
    margin_threshold=DEFAULT_MARGIN_THRESHOLD,
):
    """Run inference on one image using an already loaded model."""

    image_path = Path(image_path)

    tensor, original_size = preprocess_image(
        image_path
    )

    tensor = tensor.to(device)

    model.eval()

    with torch.inference_mode():
        logits = model(tensor)

    prediction = interpret_logits(
        logits,
        confidence_threshold=confidence_threshold,
        margin_threshold=margin_threshold,
    )

    result = {
        "timestamp_utc": datetime.now(
            timezone.utc
        ).isoformat(),
        "image": {
            "path": str(image_path.resolve()),
            "original_size": original_size,
            "preprocessed_shape": [1, 3, 224, 224],
        },
        "model": metadata or {
            "architecture": "mobilenet_v3_small",
            "classes": list(CLASS_NAMES),
            "device": str(device),
        },
        "prediction": prediction,
    }

    return result


# ------------------------------------------------------------
# 8. SAVE JSON OUTPUT
# ------------------------------------------------------------

def save_prediction_json(result, output_path):
    """Save a prediction report with an atomic file replace."""

    output_path = Path(output_path)

    output_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    fd, temporary_path = tempfile.mkstemp(
        prefix=".severity_prediction_",
        suffix=".tmp",
        dir=output_path.parent,
    )

    try:
        with os.fdopen(
            fd, "w", encoding="utf-8"
        ) as file:
            json.dump(
                result,
                file,
                indent=2,
                allow_nan=False,
            )

        os.replace(
            temporary_path,
            output_path,
        )

    finally:
        if os.path.exists(temporary_path):
            os.unlink(temporary_path)

    return output_path


# ------------------------------------------------------------
# 9. COMMAND-LINE INTERFACE
# ------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(
        description=(
            "Predict Light/Heavy rain severity using "
            "the locally trained MobileNetV3-Small."
        )
    )

    parser.add_argument(
        "--image",
        type=Path,
        required=True,
        help="Path to a rainy PNG/JPG image.",
    )

    parser.add_argument(
        "--checkpoint",
        type=Path,
        default=DEFAULT_CHECKPOINT,
        help="Trained best.pt checkpoint.",
    )

    parser.add_argument(
        "--device",
        choices=("auto", "cpu", "cuda"),
        default="auto",
    )

    parser.add_argument(
        "--confidence-threshold",
        type=float,
        default=DEFAULT_CONFIDENCE_THRESHOLD,
    )

    parser.add_argument(
        "--margin-threshold",
        type=float,
        default=DEFAULT_MARGIN_THRESHOLD,
    )

    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT,
        help="JSON output file path.",
    )

    args = parser.parse_args()

    print("=" * 65)
    print("ADAPTIVE VISION INTELLIGENCE")
    print("RAIN SEVERITY INFERENCE")
    print("=" * 65)

    model, device, metadata = load_trained_model(
        checkpoint_path=args.checkpoint,
        device=args.device,
    )

    result = predict_image(
        image_path=args.image,
        model=model,
        device=device,
        metadata=metadata,
        confidence_threshold=args.confidence_threshold,
        margin_threshold=args.margin_threshold,
    )

    save_prediction_json(
        result,
        args.output,
    )

    prediction = result["prediction"]

    print("Input image:", args.image)
    print("Checkpoint epoch:", metadata["checkpoint_epoch"])
    print("Device:", device)

    print("\nPrediction:", prediction["predicted_class"])
    print("Confidence:", prediction["confidence"])

    print("\nClass probabilities:")
    for name, probability in (
        prediction["probabilities"].items()
    ):
        print(f"  {name}: {probability:.4f}")

    print("\nUncertain:", prediction["uncertain"])

    if prediction["uncertainty_reasons"]:
        print(
            "Reasons:",
            ", ".join(
                prediction["uncertainty_reasons"]
            ),
        )

    print(
        "Suggested restoration model:",
        prediction["suggested_restoration_model"],
    )

    print(
        "Automatic routing allowed:",
        prediction["automatic_routing_allowed"],
    )

    print("Restoration executed: False")
    print("\nJSON saved to:", args.output)
    print("No training or restoration performed.")


if __name__ == "__main__":
    main()
